export function t(lang, key, fallback, vars) {
  const raw = DICT[lang]?.[key] ?? DICT.en[key] ?? fallback ?? key;
  if (!vars) return raw;
  return Object.entries(vars).reduce((s, [k, v]) => s.replaceAll(`{${k}}`, String(v)), raw);
}

